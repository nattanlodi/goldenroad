// ============================================================================
// REGISTRO PERMANENTE — notas RFT 1.0 dos PLAYOFFS por série (fonte da verdade).
// ----------------------------------------------------------------------------
// Por que este arquivo existe: as notas de cada série dos playoffs (rft.gg) são
// o insumo do overall. Antes ficavam só hardcoded nos scripts/rft-<ano>.mjs,
// soltas e sem proveniência — o que permitiu um erro de 9 pontos no Gumayusi'24
// (nota da final 71, quando o print mostra 62) passar despercebido.
//
// Cada série guarda: a fase, o placar, a URL do print rft.gg e a nota AGREGADA
// (`seriesRating`) de cada jogador — o número grande/colorido do scoreboard, que
// é o que entra no cálculo do overall. Esse é o dado CONFIRMADO por print.
// Se o print sumir do rft.gg, o número e o link ficam registrados aqui.
//
// COBERTURA: só anos/séries com PRINT CONFIRMADO. Cresce ano a ano. Nada de dado
// "a verificar" aqui. `confirmed:true` numa série = conferida print-a-print.
// ============================================================================

import type { Role } from "../types";

/** Fase de uma série de playoff. */
export type PlayoffStage = "final" | "semi" | "quarter";

/** Nota RFT de um jogador numa série. */
export interface PlayerRftSeries {
  role: Role;
  name: string;
  /** Nota agregada da série (badge grande do scoreboard). É o dado que entra no cálculo. CONFIRMADO. */
  seriesRating: number;
}

/** Um jogo individual de uma série (card "Game N" do rft.gg). */
export interface PlayoffGame {
  /** Número do jogo (1-based). */
  game: number;
  /** Quem venceu este jogo (short do time). */
  winner: string;
  /** Placar de kills do jogo, na ordem [winnerKills, loserKills] da série (time vencedor da série primeiro). */
  kills: [number, number];
}

/** Uma série de playoff registrada com sua proveniência. */
export interface PlayoffSeries {
  stage: PlayoffStage;
  /** Times pelos shorts (ex.: "T1", "BLG"). */
  winner: string;
  loser: string;
  /** Placar da série (ex.: "3-2"). */
  score: string;
  /** Jogos individuais (cards do topo do print): número, vencedor e placar de kills. */
  games: PlayoffGame[];
  /** URL do print rft.gg desta série (a fonte da verdade). */
  source?: string;
  /** true = série conferida print-a-print; os `seriesRating` batem com o scoreboard. */
  confirmed: boolean;
  /** Notas dos jogadores de AMBOS os times nesta série (vencedor primeiro, depois perdedor). */
  players: PlayerRftSeries[];
}

/** Conjunto de séries de playoff de um Worlds. */
export interface YearPlayoffs {
  year: number;
  /** Observações (ex.: quais séries têm print confirmado vs faltando). */
  notes?: string;
  series: PlayoffSeries[];
}

// ---- FASE SUÍÇA ----
// A suíça é majoritariamente Bo1 (decisivas viram Bo3). Cada partida tem o RFT
// AGREGADO por jogador (avgRftRating, extraído via scraping do rft.gg — 100% confiável)
// + os jogos com placar/vencedor. NÃO guardamos as notas por jogo individual (ficam num
// JSX serializado difícil de parsear com confiança; a média basta pro cálculo do `geral`).

/** Nota RFT de um jogador numa partida da suíça. */
export interface SwissPlayer {
  role: Role;
  name: string;
  /** Short do time (ex.: "T1", "BLG"). */
  team: string;
  /** RFT agregado do jogador nessa partida (média dos jogos, ou a nota única se Bo1). CONFIRMADO via scraping. */
  seriesRating: number;
}

/** Uma partida da fase suíça. */
export interface SwissMatch {
  /** Rodada da suíça (1..5). */
  round: number;
  winner: string;
  loser: string;
  /** Placar em jogos (ex.: "1-0", "2-1"). */
  score: string;
  /** Jogos individuais: número, vencedor e placar de kills. */
  games: PlayoffGame[];
  /** URL do match no rft.gg (fonte). */
  source?: string;
  /** true = partida conferida; os seriesRating batem com o scoreboard (avgRftRating do scraping). */
  confirmed?: boolean;
  /** Notas dos 10 jogadores (vencedor primeiro). */
  players: SwissPlayer[];
}

